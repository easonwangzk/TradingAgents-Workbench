import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const staticUrl = new URL('../tradingagents/workbench/static/', import.meta.url);
const require = createRequire(new URL('package.json', staticUrl));
const { build } = require('esbuild');
const { JSDOM } = require('jsdom');
const prototype = new JSDOM(await readFile(new URL('../docs/prototypes/research-studio.html', import.meta.url), 'utf8'));
const shared = [...prototype.window.document.querySelector('style').sheet.cssRules]
  .filter(rule => rule.selectorText && ([':root', 'html[data-theme="dark"]'].includes(rule.selectorText)
    || /data-palette|\.palette-option|\.palette-preview|\.scene-fallback|\.lens-fallback|data-ready|^\.motion-scene/.test(rule.selectorText)))
  .map(rule => rule.cssText).join('\n');
prototype.window.close();
if (!shared.includes('--cp-scene-accent') || !shared.includes('.palette-preview')) throw new Error('Prototype shared styles are incomplete');
const marker = '/* Prototype shared appearance (generated by build-workbench-studio.mjs). */';
const cssUrl = new URL('styles.css', staticUrl);
const css = await readFile(cssUrl, 'utf8');
await writeFile(cssUrl, `${css.split(marker)[0].trimEnd()}\n\n${marker}\n${shared}\n`, 'utf8');
await build({
  entryPoints: [fileURLToPath(new URL('vendor-entry.js', staticUrl))],
  nodePaths: [fileURLToPath(new URL('node_modules', staticUrl))],
  bundle: true, format: 'esm', minify: true, legalComments: 'external',
  outfile: fileURLToPath(new URL('vendor.js', staticUrl)),
});
console.log('Built same-origin studio vendor and prototype-matched palettes/scenes.');